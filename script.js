function renderAccordion(targetId, rows, isProgram = false) {
  const root = document.getElementById(targetId);
  root.innerHTML = rows
    .map((row, i) => `
      <div class="accordion-item ${i === 0 ? "open" : ""}">
        <button class="acc-trigger">${row[0]} <span>${i === 0 ? "−" : "+"}</span></button>
        <div class="acc-content">
          <p>${row[1]}</p>
          ${isProgram ? `<p><strong>${row[2]}</strong></p>` : ""}
        </div>
      </div>`)
    .join("");

  root.querySelectorAll(".acc-trigger").forEach((trigger) => {
    trigger.addEventListener("click", () => {
      const item = trigger.parentElement;
      item.classList.toggle("open");
      trigger.querySelector("span").textContent = item.classList.contains("open") ? "−" : "+";
    });
  });
}

