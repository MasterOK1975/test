function getProgramLayerClass(index) {
  if (index <= 2) return "accordion-item--start";
  if (index <= 6) return "accordion-item--deep";
  return "accordion-item--integration";
}

function renderProgramAccordion(targetId, rows) {
  const root = document.getElementById(targetId);
  if (!root) return;

  root.innerHTML = rows
    .map(
      (row, index) => `
      <div class="accordion-item ${getProgramLayerClass(index)}">
        <button class="acc-trigger" aria-expanded="false" type="button">
          <div>
            <div class="acc-index">${index + 1}</div>
            <div class="acc-title">${row.title}</div>
            <div class="acc-sub">${row.short}</div>
          </div>
          <span class="acc-plus">+</span>
        </button>
        <div class="acc-content" hidden>
          <div class="acc-zone"><strong>На этом этапе мы работаем с…</strong><br />${row.process}</div>
          <div class="acc-zone"><strong>Результат этапа</strong><br />${row.result}</div>
        </div>
      </div>`
    )
    .join("");

  setupAccordion(root);
}

function renderFaqAccordion(targetId, rows) {
  const root = document.getElementById(targetId);
  if (!root) return;

  root.innerHTML = rows
    .map(
      (row) => `
      <div class="accordion-item accordion-item--faq">
        <button class="acc-trigger" aria-expanded="false" type="button">
          <div class="acc-title">${row[0]}</div>
          <span class="acc-plus">+</span>
        </button>
        <div class="acc-content" hidden>
          <div class="acc-zone">${row[1]}</div>
        </div>
      </div>`
    )
    .join("");

  setupAccordion(root);
}

function setupAccordion(root) {
  root.querySelectorAll(".acc-trigger").forEach((trigger) => {
    trigger.addEventListener("click", () => {
      const item = trigger.parentElement;
      const content = item.querySelector(".acc-content");
      const plus = trigger.querySelector(".acc-plus");
      const isOpen = item.classList.toggle("open");

      trigger.setAttribute("aria-expanded", isOpen ? "true" : "false");
      plus.textContent = isOpen ? "−" : "+";
      if (content) {
        content.hidden = !isOpen;
      }
    });
  });
}

